app.get("/api/download/:file", (req, res) => {
  const file = path.basename(String(req.params.file));
  if (!/^[A-Za-z0-9_.-]+\.mp4$/.test(file)) return res.status(400).send("Bad file name");
  const full = path.join(RENDER_DIR, file);
  if (!fs.existsSync(full)) return res.status(404).send("File not found");
  let pretty = String(req.query.name || file).replace(/[^A-Za-z0-9_.-]/g, "_").slice(0, 80);
  if (!pretty) pretty = file;
  if (!/\.mp4$/i.test(pretty)) pretty += ".mp4";
  res.download(full, pretty);
});

