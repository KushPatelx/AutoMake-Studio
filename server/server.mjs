// ---- speed: concurrency (RENDER_CONCURRENCY env se override kar sakte ho) ----
const CORES = os.cpus().length;
const CONCURRENCY =
  Number(process.env.RENDER_CONCURRENCY) || Math.max(1, Math.floor(CORES * 0.75));

async function runRender({ jobId, compositionId, inputProps, outputName, draft = false }) {
  let bundle_ = null;
  const t0 = Date.now();
  try {
    jobs.set(jobId, { progress: 10, status: "bundling" });
    bundle_ = await getBundle();
    const bundleSec = Math.round((Date.now() - t0) / 100) / 10;

    jobs.set(jobId, { progress: 20, status: "extracting" });
    const composition = await selectComposition({
      serveUrl: bundle_.dir,
      id: compositionId,
      inputProps,
    });

    const outName = draft ? outputName.replace(/\.mp4$/, "_draft.mp4") : outputName;
    const renderStart = Date.now();
    await renderMedia({
      composition,
      serveUrl: bundle_.dir,
      codec: "h264",
      outputLocation: path.join(RENDER_DIR, outName),
      inputProps,
      concurrency: CONCURRENCY,
      ...(draft
        ? { scale: 0.5, crf: 30, x264Preset: "ultrafast" }
        : { x264Preset: "veryfast" }),
      onProgress: ({ progress }) => {
        jobs.set(jobId, {
          progress: 20 + Math.floor(progress * 79),
          status: "rendering",
        });
      },
    });

    jobs.set(jobId, {
      progress: 100,
      status: "done",
      output: `/renders/${outName}?t=${jobId}`,
      elapsedSec: Math.round((Date.now() - t0) / 1000),
      bundleSec,
      renderSec: Math.round((Date.now() - renderStart) / 100) / 10,
      bundleCached: bundle_.cached,
      draft,
    });
  } catch (err) {
    console.error(err);
    jobs.set(jobId, { progress: 0, status: "error", error: err.message });
  } finally {
    busy = false;
    if (bundle_?.temp) fs.rm(bundle_.dir, { recursive: true, force: true }, () => {});
  }
}

