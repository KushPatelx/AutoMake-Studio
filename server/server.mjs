const writeJsonAtomic = (file, obj) => {
  const tmp = `${file}.tmp`;
  fs.writeFileSync(tmp, JSON.stringify(obj));
  fs.renameSync(tmp, file);
};
const readProject = (id) => JSON.parse(fs.readFileSync(projectFile(id), "utf8"));
const cleanProjectName = (n, fallback) =>
  String(n ?? "").replace(/[\u0000-\u001f]/g, "").trim().slice(0, 80) || fallback;
const metaOf = (p) => ({ id: p.id, name: p.name, mode: p.mode, updatedAt: p.updatedAt });

app.get("/api/projects", (req, res) => {
  try {
    const out = [];
    for (const e of fs.readdirSync(PROJECT_DIR, { withFileTypes: true })) {
      if (!e.isDirectory() || !PID_RE.test(e.name)) continue;
      try {
        out.push(metaOf(readProject(e.name)));
      } catch {}
    }
    out.sort((a, b) => b.updatedAt - a.updatedAt);
    res.json(out);
  } catch (err) {
    res.status(500).json({ error: err.message });
  }
});

