// registry.ts ko folder ke hisaab se dobara banata hai (fact aur edit dono ke liye).
function writeRegistryFor(dir, file) {
  const names = fs
    .readdirSync(dir)
    .filter((f) => f.endsWith(".tsx"))
    .map((f) => f.replace(/\.tsx$/, ""))
    .filter((n) => NAME_RE.test(n))
    .sort();

  const imports = names.map((n, i) => `import * as M${i} from "./${n}";`).join("\n");
  const items = names
    .map((n, i) => `  { name: "${n}", component: pick(M${i}, "${n}") },`)
    .join("\n");

  const code = `// AUTO-GENERATED by server/server.mjs - isko haath se edit mat karo.
import type { ComponentType } from "react";
${imports}

const pick = (mod: any, name: string): ComponentType<any> =>
  mod[name] ??
  mod.default ??
  (Object.values(mod).find((v) => typeof v === "function") as ComponentType<any>);

export const customTemplates: {
  name: string;
  component: ComponentType<any>;
}[] = [
${items}
];
`;
  fs.writeFileSync(file, code, "utf8");
}
