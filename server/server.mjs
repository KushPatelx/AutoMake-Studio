async function saveTemplate(req, res, dir, regenerate) {
  try {
    const name = cleanName(req.body?.name);
    const code = String(req.body?.code ?? "");

    if (!NAME_RE.test(name)) {
      return res.status(400).json({
        error: "Name sirf letters/numbers/underscore ho, aur letter se shuru (e.g. GlitchTheme).",
      });
    }
    if (!code.trim()) return res.status(400).json({ error: "Code khali hai." });

    const exportsName = new RegExp(
      `export\\s+(const|let|var|function|class)\\s+${name}\\b|export\\s+default\\b|export\\s*\\{[^}]*\\b${name}\\b`,
    );
    if (!exportsName.test(code)) {
      return res.status(400).json({
        error: `Code mein "export const ${name}" nahi mila. Component ka naam bilkul "${name}" hona chahiye.`,
      });
    }

    if (esbuild) {
      try {
        await esbuild.transform(code, { loader: "tsx" });
      } catch (e) {
        const first = e?.errors?.[0];
        const where = first?.location ? ` (line ${first.location.line})` : "";
        return res.status(400).json({
          error: `Code mein syntax error${where}: ${first?.text || e.message}`,
        });
      }
    }

    fs.writeFileSync(path.join(dir, `${name}.tsx`), code, "utf8");
    regenerate();
    res.json({ success: true, message: "Template successfully generated!" });
  } catch (err) {
    console.error(err);
    res.status(500).json({ error: err.message });
  }
}

function deleteTemplate(req, res, dir, regenerate) {
  try {
    const name = cleanName(req.params.name);
    if (!NAME_RE.test(name)) return res.status(400).json({ error: "Invalid name" });

    const filePath = path.join(dir, `${name}.tsx`);
    if (!fs.existsSync(filePath)) {
      return res.status(404).json({ error: "Template not found on server." });
    }
    fs.unlinkSync(filePath);
    regenerate();
    res.json({ success: true, message: "Template deleted successfully!" });
  } catch (err) {
    console.error("Delete error:", err);
    res.status(500).json({ error: err.message });
  }
}

