app.put("/api/projects/:id", (req, res) => {
  const id = req.params.id;
  if (!PID_RE.test(id)) return res.status(400).json({ error: "Invalid id" });
  try {
    const project = readProject(id);
    if (req.body?.name !== undefined) project.name = cleanProjectName(req.body.name, project.name);
    if (req.body?.data !== undefined) project.data = req.body.data;
    if (Array.isArray(req.body?.mediaIds)) {
      project.mediaIds = req.body.mediaIds.map(String).filter((m) => MID_RE.test(m)).slice(0, 200);
      // jo media ab project me nahi hai use disk se hata do
      const mediaDir = path.join(projectPath(id), "media");
      const keep = new Set(project.mediaIds);
      for (const f of fs.readdirSync(mediaDir)) {
        const base = f.replace(/\.json$/, "");
        if (!keep.has(base)) fs.rmSync(path.join(mediaDir, f), { force: true });
      }
    }
    project.updatedAt = Date.now();
    writeJsonAtomic(projectFile(id), project);
    res.json(metaOf(project));
  } catch {
    res.status(404).json({ error: "Project not found" });
  }
});

app.put(
  "/api/projects/:id/media/:mid",
  express.raw({ type: () => true, limit: "90mb" }),
  (req, res) => {
    const { id, mid } = req.params;
    if (!PID_RE.test(id) || !MID_RE.test(mid)) return res.status(400).json({ error: "Invalid id" });
    try {
      if (!fs.existsSync(projectFile(id))) return res.status(404).json({ error: "Project not found" });
      if (!Buffer.isBuffer(req.body) || req.body.length === 0) {
        return res.status(400).json({ error: "Empty file" });
      }
      const dir = path.join(projectPath(id), "media");
      fs.mkdirSync(dir, { recursive: true });
      fs.writeFileSync(path.join(dir, mid), req.body);
      fs.writeFileSync(
        path.join(dir, `${mid}.json`),
        JSON.stringify({
          name: decodeURIComponent(String(req.headers["x-file-name"] || "file")).slice(0, 120),
          type: String(req.headers["content-type"] || "application/octet-stream"),
        }),
      );
      res.json({ ok: true });
    } catch (err) {
      res.status(500).json({ error: err.message });
    }
  },
);

