// ---- speed: bundle cache ----
// Pehle har render pe poora project bundle hota tha (sabse slow hissa). Ab bundle ek baar banta hai
// aur tab tak reuse hota hai jab tak src/ me kuch badla na ho. Nayi uploads bundle ke public/ me copy hoti hain.
const SRC_DIR = path.join(ROOT, "src");
let bundleCache = { dir: null, sig: null };

function srcSignature() {
  let count = 0;
  let newest = 0;
  const walk = (dir) => {
    for (const e of fs.readdirSync(dir, { withFileTypes: true })) {
      const full = path.join(dir, e.name);
      if (e.isDirectory()) walk(full);
      else {
        count++;
        newest = Math.max(newest, fs.statSync(full).mtimeMs);
      }
    }
  };
  walk(SRC_DIR);
  for (const f of ["package.json", "remotion.config.ts"]) {
    const fp = path.join(ROOT, f);
    if (fs.existsSync(fp)) {
      count++;
      newest = Math.max(newest, fs.statSync(fp).mtimeMs);
    }
  }
  return `${count}:${newest}`;
}

function syncAssets(bundleDir) {
  for (const sub of ["images", "audio", "edit", "facts"]) {
    const from = path.join(PUBLIC_DIR, "assets", sub);
    const to = path.join(bundleDir, "public", "assets", sub);
    if (!fs.existsSync(from)) continue;
    fs.rmSync(to, { recursive: true, force: true });
    fs.mkdirSync(path.dirname(to), { recursive: true });
    fs.cpSync(from, to, { recursive: true });
  }
}

async function getBundle() {
  const sig = srcSignature();
  if (
    bundleCache.dir &&
    bundleCache.sig === sig &&
    fs.existsSync(path.join(bundleCache.dir, "public"))
  ) {
    syncAssets(bundleCache.dir);
    return { dir: bundleCache.dir, cached: true, temp: false };
  }
  if (bundleCache.dir) {
    fs.rm(bundleCache.dir, { recursive: true, force: true }, () => {});
    bundleCache = { dir: null, sig: null };
  }
  const dir = await bundle({
    entryPoint: path.resolve(ROOT, "src", "index.ts"),
    publicDir: PUBLIC_DIR,
    webpackOverride: (c) => c,
  });
  // Agar bundle ka folder structure alag nikla to cache band, purana (safe) tareeka
  if (fs.existsSync(path.join(dir, "public"))) {
    bundleCache = { dir, sig };
    return { dir, cached: false, temp: false };
  }
  return { dir, cached: false, temp: true };
}

const cleanupBundle = () => {
  if (bundleCache.dir) fs.rmSync(bundleCache.dir, { recursive: true, force: true });
};
process.on("exit", cleanupBundle);
